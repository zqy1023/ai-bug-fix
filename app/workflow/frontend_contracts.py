"""导出后端正式模型与主工作流阶段，供前端构建及契约测试使用。"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from app.workflow.contracts import Assessment, ExecutionResult
from workbench.projections import task_stages
from workbench.view_models import ActionAvailability, DeliveryView


def ts_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if schema.get("type") == "object":
        value = schema.get("additionalProperties")
        return f"Record<string, {ts_type(value)}>" if isinstance(value, dict) else "Record<string, unknown>"
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(ts_type(value) for value in schema["anyOf"])
    if schema.get("type") == "array":
        return f"Array<{ts_type(schema['items'])}>"
    return {"string": "string", "boolean": "boolean", "integer": "number", "number": "number", "null": "null"}.get(schema.get("type"), "unknown")


def generate() -> str:
    definitions = {}
    for model in (ExecutionResult, Assessment, ActionAvailability, DeliveryView):
        schema = model.model_json_schema()
        definitions.update(schema.pop("$defs", {}))
        definitions[model.__name__] = schema
    lines = ["// Generated by python -m app.workflow.frontend_contracts. Do not edit."]
    for name, schema in definitions.items():
        lines.append(f"export interface {name} {{")
        required = set(schema.get("required", []))
        for key, value in schema["properties"].items():
            optional = "" if key in required else "?"
            lines.append(f"  {key}{optional}: {ts_type(value)};")
        lines.append("}\n")
    lines.append("export const WORKFLOW_STAGES = " + json.dumps(task_stages(), ensure_ascii=False, indent=2) + ";\n")
    return "\n".join(lines)


if __name__ == "__main__":
    target = Path(__file__).resolve().parents[2] / "frontend/src/lib/workflow.generated.ts"
    target.write_text(generate(), encoding="utf-8")
